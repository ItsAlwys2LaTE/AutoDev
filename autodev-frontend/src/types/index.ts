/**
 * Specific conditions that a software feature must satisfy to be accepted.
 * Corresponds to backend/models.py:AcceptanceCriteria
 */
export interface AcceptanceCriteria {
  /** Unique identifier for the acceptance criterion, e.g., 'AC-1' */
  id: string;
  /** Clear, testable description of the condition */
  description: string;
  /** What the system should do if the condition is met */
  expected_behavior: string;
}

/**
 * A single user story representing a discrete piece of functionality.
 * Corresponds to backend/models.py:UserStory
 */
export interface UserStory {
  /** Short title of the feature */
  title: string;
  /** The user persona, e.g., 'As a registered user' */
  as_a: string;
  /** The action the user wants to perform */
  i_want_to: string;
  /** The business value or expected benefit */
  so_that: string;
  /** Acceptance criteria required for this story */
  acceptance_criteria: AcceptanceCriteria[];
}

/**
 * Structured requirements document synthesized by the Requirements Agent.
 * Corresponds to backend/models.py:RequirementsDocument
 */
export interface RequirementsDocument {
  /** Inferred title of the project or feature */
  project_title: string;
  /** Brief summary of what is being built */
  overview: string;
  /** All user stories required to build the feature */
  user_stories: UserStory[];
}

// =============================================================================
// 2. PHASE 2 MODELS: SYSTEM DESIGN & EXECUTION BLUEPRINTS
// =============================================================================

/**
 * Blueprint for an individual file to be generated.
 * Corresponds to backend/models.py:FileBlueprint
 */
export interface FileBlueprint {
  /** Name of the file with extension, e.g., 'validator.py', 'app.tsx' */
  file_name: string;
  /** Primary architectural responsibility of this file */
  purpose: string;
  /** List of standard libraries or packages needed, e.g., ['re', 'fastapi'] */
  dependencies: string[];
  /** Rough logical sketch or pseudo-implementation of the functions/classes */
  pseudocode: string;
}

/**
 * Structured system architecture blueprint synthesized by the Design Agent.
 * Corresponds to backend/models.py:SystemDesignBlueprint
 */
export interface SystemDesignBlueprint {
  /** High-level explanation of the chosen architectural design */
  architecture_overview: string;
  /** Selected languages, libraries, and frameworks */
  tech_stack: string[];
  /** Docker image used for sandbox execution and dev server */
  docker_image: string;
  /** Command to start the dev server bound to 0.0.0.0; 'NONE' if no server */
  dev_server_command: string;
  /** Internal port the dev server binds to; 0 if none */
  dev_server_port: number;
  /** Terminal command to execute tests, e.g., 'pytest' or 'npm run build' */
  run_tests_command: string;
  /** Manifest of all files that need to be coded */
  files: FileBlueprint[];
}

