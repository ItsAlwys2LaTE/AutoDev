/**
 * A single generated source code file.
 * Corresponds to backend/models.py:CodeFile
 */
export interface CodeFile {
  /** Relative path of the file with extension, e.g., 'src/validator.py' */
  file_name: string;
  /** Complete, runnable UTF-8 source code for this file */
  source_code: string;
  /** Optional file path alias for backward compatibility */
  path?: string;
}

/**
 * Complete codebase generated by the CodeGen Agent or Integrator.
 * Corresponds to backend/models.py:GeneratedCodeBase
 */
export interface GeneratedCodeBase {
  /** List of all source code files in the codebase */
  files: CodeFile[];
}

/**
 * Result of running tests or build verification in the Docker sandbox.
 * Corresponds to backend/models.py:ExecutionResult
 */
export interface ExecutionResult {
  /** True if tests or build passed cleanly (exit code 0), False otherwise */
  success: boolean;
  /** Combined stdout and stderr logs from the execution */
  logs: string;
}

// =============================================================================
// 4. PHASE 3 MODELS: ARBITRATION, CRITIQUES & ADJUDICATION
// =============================================================================

/**
 * Numeric severity score assigned by a critic agent (0 = perfect, 10 = critical failure).
 */
export type CriticScore = number;

/**
 * Dimension breakdown of critic scores.
 */
export interface CriticScoreBreakdown {
  correctness: number;
  architecture?: number;
  completeness?: number;
  composite?: number;
}

/**
 * Standardized qualitative and quantitative feedback from a critic agent.
 * Corresponds to backend/models.py:CriticFeedback
 */
export interface CriticFeedback {
  /** Name of the critic, e.g., 'Correctness Critic', 'Architecture Critic' */
  critic_name: string;
  /** Score from 0 (perfect) to 10 (critical failure) */
  severity_score: CriticScore;
  /** Specific issues and regressions identified */
  issues_list: string[];
  /** Summary evaluation comments */
  overall_comments: string;
}

/**
 * Valid adjudication verdicts.
 */
export type AdjudicatorVerdict = 'pass' | 'revise' | 'error';

/**
 * Final decision made by the Adjudicator agent based on critic feedback.
 * Corresponds to backend/models.py:AdjudicatorDecision
 */
export interface AdjudicatorDecision {
  /** Verdict: strictly 'pass', 'revise', or 'error' */
  verdict: AdjudicatorVerdict;
  /** Actionable revision instructions for CodeGen if 'revise', error description if 'error', approval message if 'pass' */
  revision_plan: string;
  /** Weighted composite severity score (Correctness 50%, Architecture 20%, Completeness 30%) */
  weighted_composite?: number | null;
  /** Improvement delta compared to previous revision */
  delta?: number | null;
  /** Dynamic revision budget calculated as min(5, ceil(composite / 3)) */
  dynamic_budget?: number | null;
  /** True if early stop was triggered due to diminishing returns (delta <= 1.0) */
  early_stop?: boolean | null;
}

