/**
 * Specification for a decomposed component node in the DAG.
 * Corresponds to backend/models.py:ComponentSpec
 */
export interface ComponentSpec {
  /** Unique kebab-case identifier, e.g., 'auth-system', 'data-pipeline' */
  component_id: string;
  /** Human-readable title, e.g., 'User Authentication System' */
  component_name: string;
  /** Functional scope boundaries and responsibilities */
  description: string;
  /** Focused requirements text scoped strictly to this component */
  scoped_requirements: string;
  /** IDs of upstream components this component depends on */
  dependencies_on: string[];
  /** Execution priority order (1 = first) */
  priority_order: number;
  /** Optional Docker image override for this specific component */
  docker_image?: string | null;
  /** Optional tech stack override for this specific component */
  tech_stack?: string[] | null;
}

/**
 * Master Architect Agent output decomposing projects into multi-component DAGs.
 * Corresponds to backend/models.py:ComponentDecomposition
 */
export interface ComponentDecomposition {
  /** False for single-pass pipeline; True for multi-component DAG */
  is_complex: boolean;
  /** High-level product vision describing the overall system */
  project_overview: string;
  /** Common tech stack used across components */
  shared_tech_stack: string[];
  /** Base Docker image used across components */
  shared_docker_image: string;
  /** Decomposed component list; must have >= 3 components if is_complex is True */
  components: ComponentSpec[];
  /** Cross-component routing, shared state, navigation, and integration strategy */
  integration_strategy: string;
}

/**
 * Fully tested and critic-approved output of a single component.
 * Corresponds to backend/models.py:ComponentResult
 */
export interface ComponentResult {
  /** The component_id this result belongs to */
  component_id: string;
  /** Human-readable component name */
  component_name: string;
  /** Design blueprint used for this component */
  blueprint: SystemDesignBlueprint;
  /** Passing, tested source code for this component */
  codebase: GeneratedCodeBase;
  /** Passing sandbox execution result */
  execution_result: ExecutionResult;
}

