/**
 * Master lifecycle status of the AutoDev pipeline.
 */
export type PipelineStatus = 'idle' | 'running' | 'aborted' | 'completed';

/**
 * Discrete in-flight phase marker used for crash recovery and state restoration.
 * Corresponds to backend/index.html:inFlightPhase recovery matrix.
 */
export type InFlightPhase =
  | 'requirements'
  | 'decomposition'
  | 'single_design'
  | 'single_codegen'
  | 'single_execution'
  | 'single_critics'
  | 'component_dag'
  | 'integration'
  | 'documentation'
  | null;

/**
 * Pipeline generation mode toggle.
 */
export type AppMode = 'QUICK' | 'COMPLEX';

/**
 * Cumulative token counts and INR monetary cost tracking.
 * Reference rates: Gemini 1.5 Flash ($0.075 prompt / $0.30 completion per 1M tokens, 84 INR/USD).
 */
export interface SessionUsage {
  /** Total prompt tokens consumed */
  prompt: number;
  /** Total completion / candidate tokens generated */
  completion: number;
  /** Calculated session cost in Indian Rupees (INR) */
  cost: number;
}

/**
 * Token usage sentinel extracted from stream terminator: \n__USAGE__{prompt},{completion}
 */
export interface TokenUsageSentinel {
  promptTokens: number;
  completionTokens: number;
}

/**
 * Formatted token cost breakdown for the header metrics display.
 */
export interface TokenCostBreakdown {
  promptTokens: number;
  completionTokens: number;
  totalTokens: number;
  costUsd: number;
  costInr: number;
  formattedInr: string;
}

/**
 * Semantic severity classification for terminal logs.
 */
export type LogLevel =
  | 'error'
  | 'warning'
  | 'fallback'
  | 'agent'
  | 'success'
  | 'differential'
  | 'system'
  | 'standard';

/**
 * Real-time log message received from SSE /api/logs/stream.
 */
export interface LogMessage {
  /** Unique client-side identifier or sequence number */
  id: string;
  /** Timestamp string, e.g., '2026-09-22 19:30:00' */
  timestamp: string;
  /** Message content with internal newlines unescaped */
  message: string;
  /** Semantic classification driving terminal syntax coloring */
  level: LogLevel;
  /** Raw unparsed SSE line */
  raw: string;
}

